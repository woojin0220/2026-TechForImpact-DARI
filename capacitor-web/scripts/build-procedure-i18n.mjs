import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const languages=['ko','en','fr','ru','ar','fa'];
const catalog=Object.fromEntries(languages.map(lang=>[lang,JSON.parse(fs.readFileSync(path.join(root,'src/procedure/locales',lang+'.json'),'utf8'))]));
const keys=Object.keys(catalog.ko).sort();
for(const lang of languages){
  if(JSON.stringify(Object.keys(catalog[lang]).sort())!==JSON.stringify(keys))throw new Error('Incomplete procedure catalog: '+lang);
  for(const key of keys)if(typeof catalog[lang][key]!=='string'||!catalog[lang][key].trim())throw new Error('Empty procedure message: '+lang+'/'+key);
}
const runtime=`
const requested=new URLSearchParams(location.search).get('lang')||'ko';
const language=Object.hasOwn(catalog,requested)?requested:'en';
const sourceKeys=new Map(Object.entries(catalog.ko).map(([key,value])=>[value,key]));
function t(key){return catalog[language][key]??catalog.en[key]??catalog.ko[key]??key;}
function translate(root){
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);const nodes=[];
 while(walker.nextNode())if(!walker.currentNode.parentElement?.closest('script,style'))nodes.push(walker.currentNode);
 for(const node of nodes){const raw=node.nodeValue,trimmed=raw.trim(),key=sourceKeys.get(trimmed);if(key)node.nodeValue=raw.replace(trimmed,()=>t(key));}
 for(const el of root.querySelectorAll('[aria-label],[title]'))for(const attr of ['aria-label','title']){const raw=el.getAttribute(attr),key=sourceKeys.get(raw);if(key)el.setAttribute(attr,t(key));}
}
document.documentElement.lang=language;
document.documentElement.dir=['ar','fa'].includes(language)?'rtl':'ltr';
window.DariProcedureI18n=Object.freeze({language,t,translate});
`;
fs.writeFileSync(path.join(root,'public/procedure-i18n.js'),'/* Generated by scripts/build-procedure-i18n.mjs. Edit src/procedure/locales instead. */\n(()=>{\nconst catalog='+JSON.stringify(catalog)+';\n'+runtime+'\n})();\n');
console.log('Procedure languages: '+languages.join(', ')+' / '+keys.length+' messages each');
